/** Typecheck and bundle the app-screen stress test into site/app-stress/{app.js,app.css}. */
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from '../display/node_modules/esbuild/lib/main.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const tools = join(root, 'display/node_modules');
const pageDir = join(root, 'site/app-stress');
const src = join(pageDir, 'src');
const elementalSrc = join(root, 'packages/elemental-title/src');
// The Living Titles runtime as built for the NovelExpanded mock, typed by the package declarations.
const livingRuntime = join(root, 'display/novel-expanded/runtime/index.js');
const livingTypes = join(root, 'packages/living-titles/src/index.d.ts');
const posix = (p) => p.replace(/\\/g, '/');

const check = mkdtempSync(join(tmpdir(), 'app-stress-typecheck-'));
try {
  writeFileSync(join(check, 'tsconfig.json'), JSON.stringify({
    compilerOptions: {
      target: 'ES2022', module: 'ESNext', moduleResolution: 'bundler', strict: true, noEmit: true,
      jsx: 'react-jsx', lib: ['ES2022', 'DOM', 'DOM.Iterable'],
      paths: {
        react: [posix(join(tools, '@types/react/index.d.ts'))],
        'react-dom/client': [posix(join(tools, '@types/react-dom/client.d.ts'))],
        'react/jsx-runtime': [posix(join(tools, '@types/react/jsx-runtime.d.ts'))],
        '@seihouse/living-titles': [posix(livingTypes)],
      },
    },
    include: [posix(join(src, '**/*.ts')), posix(join(src, '**/*.tsx')),
      posix(join(elementalSrc, '**/*.ts')), posix(join(elementalSrc, '**/*.tsx'))],
  }));
  const tsc = spawnSync(process.execPath, [join(tools, 'typescript/bin/tsc'), '--project', join(check, 'tsconfig.json')], { encoding: 'utf8' });
  if (tsc.status !== 0) throw new Error(`App stress test TypeScript check failed:\n${tsc.stdout}${tsc.stderr}`);
} finally {
  rmSync(check, { recursive: true, force: true });
}

const built = await build({
  entryPoints: [join(src, 'main.tsx')], bundle: true, format: 'esm', platform: 'browser', target: ['es2022'],
  jsx: 'automatic', minify: true, define: { 'process.env.NODE_ENV': '"production"' }, nodePaths: [tools],
  alias: { '@seihouse/living-titles': livingRuntime }, write: false,
});
const js = '/* Generated by site/build_app_stress.mjs — do not edit directly. */\n' + built.outputFiles[0].text.replace(/\r\n/g, '\n');
writeFileSync(join(pageDir, 'app.js'), js, 'utf8');

const css = '/* Generated by site/build_app_stress.mjs — elemental-title.css + src/app.css */\n\n' +
  readFileSync(join(elementalSrc, 'elemental-title.css'), 'utf8').replace(/\r\n/g, '\n') + '\n' +
  readFileSync(join(src, 'app.css'), 'utf8').replace(/\r\n/g, '\n');
writeFileSync(join(pageDir, 'app.css'), css, 'utf8');
console.log(`App stress test bundled -> site/app-stress/app.js (${(Buffer.byteLength(js) / 1024).toFixed(1)} KB) & app.css`);
