/** Typecheck and bundle the standalone Elemental Title Lab into display/elemental/{lab.js,lab.css}. */
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from './node_modules/esbuild/lib/main.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const tools = join(root, 'display/node_modules');
const labDir = join(root, 'display/elemental');
const labSrc = join(labDir, 'src');
const pkgSrc = join(root, 'packages/elemental-title/src');

const toPosix = (p) => p.replace(/\\/g, '/');

// Strict TypeScript check across lab sources and package sources
const checkTmp = mkdtempSync(join(tmpdir(), 'elemental-lab-typecheck-'));
try {
  writeFileSync(
    join(checkTmp, 'tsconfig.json'),
    JSON.stringify({
      compilerOptions: {
        target: 'ES2022',
        module: 'ESNext',
        moduleResolution: 'bundler',
        strict: true,
        noEmit: true,
        jsx: 'react-jsx',
        lib: ['ES2022', 'DOM', 'DOM.Iterable'],
        paths: {
          react: [toPosix(join(tools, '@types/react/index.d.ts'))],
          'react-dom/client': [toPosix(join(tools, '@types/react-dom/client.d.ts'))],
          'react/jsx-runtime': [toPosix(join(tools, '@types/react/jsx-runtime.d.ts'))],
        },
      },
      include: [
        toPosix(join(labSrc, '**/*.ts')),
        toPosix(join(labSrc, '**/*.tsx')),
        toPosix(join(pkgSrc, '**/*.ts')),
        toPosix(join(pkgSrc, '**/*.tsx')),
      ],
    })
  );
  const tsc = spawnSync(
    process.execPath,
    [join(tools, 'typescript/bin/tsc'), '--project', join(checkTmp, 'tsconfig.json')],
    { encoding: 'utf8' }
  );
  if (tsc.status !== 0) {
    throw new Error(`Elemental Title Lab TypeScript check failed:\n${tsc.stdout}${tsc.stderr}`);
  }
} finally {
  rmSync(checkTmp, { recursive: true, force: true });
}

const built = await build({
  entryPoints: [join(labSrc, 'main.tsx')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  minify: true,
  define: { 'process.env.NODE_ENV': '"production"' },
  nodePaths: [tools],
  write: false,
});

const js =
  '/* Generated by display/build_elemental_lab.mjs — do not edit directly. */\n' +
  built.outputFiles[0].text.replace(/\r\n/g, '\n');
writeFileSync(join(labDir, 'lab.js'), js, 'utf8');

const pkgCss = readFileSync(join(pkgSrc, 'elemental-title.css'), 'utf8').replace(/\r\n/g, '\n');
const baseCss = readFileSync(join(labSrc, 'lab-base.css'), 'utf8').replace(/\r\n/g, '\n');
const combinedCss =
  '/* Generated by display/build_elemental_lab.mjs — combines elemental-title.css + lab-base.css */\n\n' +
  pkgCss +
  '\n' +
  baseCss;
writeFileSync(join(labDir, 'lab.css'), combinedCss, 'utf8');

console.log(
  `Elemental Title Lab bundled -> display/elemental/lab.js (${(Buffer.byteLength(js) / 1024).toFixed(1)} KB) & display/elemental/lab.css`
);
